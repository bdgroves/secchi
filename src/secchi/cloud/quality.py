"""Quality flags in SQL Server, ported from the export's DuckDB rules.

The rules are not rewritten by hand: the T-SQL is generated from the same
``IMPOSSIBLE`` list and ``OPTICAL_CHANNELS`` the export and the watcher use,
so there is one definition of "impossible" in the project.

Two views come out of it (cloud/out/03_quality.sql, run after every load
and sync):

``secchi.obs_flagged``  every reading, with names, and ``quality_flag``
                        (a ';'-joined list, NULL when clean).
``secchi.obs_clean``    the readings with no blocking flag. The raw table
                        is never changed; this is the fix, as a view.

And one check, like the reconcile: for each flag, SQL Server's count of
flagged readings must equal DuckDB's (``secchi.export``'s ``obs_flagged``).

Ported: impossible_range, channel_scramble, exo_sat_sea_level,
negative_turbidity, negative_chlorophyll, negative_phycocyanin, ph_zero.
Not ported yet: repeated_hour and the two duplicate flags.
"""

from __future__ import annotations

from secchi.export import OPTICAL_CHANNELS
from secchi.sources.watch import IMPOSSIBLE

PORTED = ["impossible_range", "channel_scramble", "exo_sat_sea_level",
          "negative_turbidity", "negative_chlorophyll", "negative_phycocyanin",
          "ph_zero"]

# Flags that make a reading unusable. The others are notes (a calibration
# offset, a known reference-pressure issue) and stay in obs_clean.
BLOCKING = ["impossible_range", "channel_scramble", "ph_zero"]


def _impossible_tsql() -> str:
    return " OR ".join(
        f"(n.sensor_type = '{inst}' AND n.variable = '{var}' "
        f"AND (n.value < {lo} OR n.value > {hi}) "
        f"AND NOT (n.variable = 'pH' AND n.value = 0))"
        for inst, var, lo, hi in IMPOSSIBLE)


def quality_sql() -> str:
    optical = ", ".join(f"'{c}'" for c in OPTICAL_CHANNELS)
    blocking = " AND ".join(
        f"CHARINDEX('{f}', ISNULL(quality_flag, '')) = 0" for f in BLOCKING)
    return f"""-- Generated by secchi.cloud.quality from the export's rules. Do not edit.
SET NOCOUNT ON;
GO
CREATE OR ALTER VIEW secchi.obs_named AS
SELECT o.record_uuid, s.site, t.sensor_type, o.ts, v.variable, o.value
FROM secchi.obs AS o
JOIN secchi.site AS s        ON s.site_id = o.site_id
JOIN secchi.sensor_type AS t ON t.sensor_type_id = o.sensor_type_id
JOIN secchi.variable AS v    ON v.variable_id = o.variable_id;
GO
CREATE OR ALTER VIEW secchi.obs_flagged AS
WITH scramble_optical AS (       -- oxygen saturation in the concentration field
    SELECT DISTINCT site, ts FROM secchi.obs_named
    WHERE sensor_type = 'ExoSensor' AND variable = 'Do_mgL' AND value > 20),
scramble_full AS (               -- oxygen saturation in the temperature field
    SELECT DISTINCT site, ts FROM secchi.obs_named
    WHERE sensor_type = 'ExoSensor' AND variable = 'Temp' AND value > 35)
SELECT n.record_uuid, n.site, n.sensor_type, n.ts, n.variable, n.value,
       NULLIF(CONCAT_WS(';',
         CASE WHEN {_impossible_tsql()} THEN 'impossible_range' END,
         CASE WHEN n.sensor_type = 'ExoSensor'
               AND ((f.site IS NOT NULL AND n.variable <> 'BattV_Min')
                 OR (t.site IS NOT NULL AND n.variable IN ({optical})))
              THEN 'channel_scramble' END,
         CASE WHEN n.sensor_type = 'ExoSensor' AND n.variable = 'Do_percent'
              THEN 'exo_sat_sea_level' END,
         CASE WHEN n.sensor_type = 'ExoSensor' AND n.variable = 'Turbidity' AND n.value < 0
              THEN 'negative_turbidity' END,
         CASE WHEN n.sensor_type = 'ExoSensor' AND n.variable = 'Chl_a' AND n.value < 0
              THEN 'negative_chlorophyll' END,
         CASE WHEN n.sensor_type = 'ExoSensor' AND n.variable = 'phycocyanin' AND n.value < 0
              THEN 'negative_phycocyanin' END,
         CASE WHEN n.sensor_type = 'ExoSensor' AND n.variable = 'pH' AND n.value = 0
              THEN 'ph_zero' END
       ), '') AS quality_flag
FROM secchi.obs_named AS n
LEFT JOIN scramble_optical AS t ON t.site = n.site AND t.ts = n.ts
LEFT JOIN scramble_full AS f    ON f.site = n.site AND f.ts = n.ts;
GO
CREATE OR ALTER VIEW secchi.obs_clean AS
SELECT record_uuid, site, sensor_type, ts, variable, value, quality_flag
FROM secchi.obs_flagged
WHERE {blocking};
GO
{MAP_VIEWS}"""


# Views for a GIS client (QGIS's MS SQL provider, an ArcGIS Pro query
