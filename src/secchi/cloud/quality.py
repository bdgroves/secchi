def flag_counts_tsql() -> str:
    cols = ",\n       ".join(
        f"SUM(CASE WHEN CHARINDEX('{f}', quality_flag) > 0 THEN 1 ELSE 0 END) AS [{f}]"
        for f in PORTED)
    return f"SET NOCOUNT ON;\nSELECT {cols}\nFROM secchi.obs_flagged;"


def flag_counts_duck(con) -> dict[str, int]:
    """DuckDB's counts, from the export's own obs_flagged view."""
    from secchi.export import _prepare_observations
    from secchi.query import _glob

    _prepare_observations(con, _glob("observations"), set())
    cols = ", ".join(f"sum(CASE WHEN contains(quality_flag, '{f}') THEN 1 ELSE 0 END)"
                     for f in PORTED)
    row = con.sql(f"SELECT {cols} FROM obs_flagged").fetchone()
    return {f: int(v or 0) for f, v in zip(PORTED, row, strict=True)}
